"""Run: python scripts/test_check_no_ai_credit.py"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from check_no_ai_credit import credits  # noqa: E402

clean = "Fix a thing\n\nSigned-off-by: Ana Player <ana@example.com>\n"
assert credits(clean) == []
# Human co-authors are fine.
assert credits("Fix\n\nCo-Authored-By: Ana Player <ana@example.com>\n") == []
# Tool co-authors, vendor addresses and generated-with footers are not.
assert credits("Fix\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\n") == ["Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"]
assert len(credits("Fix\n\nco-authored-by: Codex <codex@example.com>\n")) == 1
assert len(credits("Fix\n\nCo-authored-by: Copilot <copilot@github.com>\n")) == 1
assert len(credits("Body\n\n\U0001F916 Generated with [Claude Code](https://claude.com/claude-code)\n")) == 1
assert len(credits("Body\n\nGenerated by ChatGPT\n")) == 1
# Product names in ordinary prose are not credits.
assert credits("Companion: Anthropic provider, claude-opus-5-5 by default\n") == []
assert credits("robots.txt names ClaudeBot and GPTBot\n") == []
print("ok")
